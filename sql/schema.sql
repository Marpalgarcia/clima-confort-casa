-- 1. Tabla de habitaciones (en principio quiero empezar con mi cuarto y luego ya escalar a toda la casa)
CREATE TABLE rooms (
  id TEXT PRIMARY KEY,
  nombre TEXT NOT NULL,
  umbral_frio_dia NUMERIC DEFAULT 14.0,
  umbral_calor_dia NUMERIC DEFAULT 28.0,
  umbral_frio_noche NUMERIC DEFAULT 17.5,
  umbral_calor_noche NUMERIC DEFAULT 21.5,
  histeresis NUMERIC DEFAULT 0.8,
  estado_alerta TEXT DEFAULT 'NORMAL', -- 'NORMAL', 'CALOR', 'FRIO'
  ultima_alerta TIMESTAMPTZ
);

-- 2. Tabla de lecturas de temperatura, humedad y sensación térmica
CREATE TABLE readings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id TEXT REFERENCES rooms(id) ON DELETE CASCADE,
  temperatura NUMERIC NOT NULL,
  humedad NUMERIC NOT NULL,
  sensacion_termica NUMERIC NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Índice para consultar rápido las lecturas recientes por habitación
CREATE INDEX idx_readings_room_time ON readings (room_id, created_at DESC);

-- 3. Historial de alertas enviadas al móvil
CREATE TABLE alerts_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id TEXT REFERENCES rooms(id) ON DELETE CASCADE,
  tipo_alerta TEXT NOT NULL,
  mensaje TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

